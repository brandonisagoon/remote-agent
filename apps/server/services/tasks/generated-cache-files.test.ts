import { afterEach, expect, test } from "bun:test";
import { chmodSync, linkSync, mkdirSync, mkdtempSync, realpathSync, rmSync, rmdirSync, symlinkSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { scanOwnedGeneratedCache } from "./generated-cache-files.ts";

const roots: string[] = [];
afterEach(() => { for (const root of roots.splice(0)) rmSync(root, { recursive: true, force: true }); });
function fixture() {
  const parent = realpathSync(mkdtempSync(path.join(os.tmpdir(), "generated-cache-"))); roots.push(parent);
  const root = path.join(parent, "node_modules"), cache = path.join(root, ".vite"), file = path.join(cache, "metadata.json");
  mkdirSync(cache, { recursive: true }); writeFileSync(file, '{"generation":1}'); chmodSync(root, 0o777); chmodSync(file, 0o666);
  return { parent, root, cache, file };
}
test("inventories writable generated bytes without changing permissions, and detects changed bytes with the same root", () => {
  const f = fixture(), first = scanOwnedGeneratedCache(f.root), repeated = scanOwnedGeneratedCache(f.root);
  expect(repeated).toEqual(first); expect(first.entries).toHaveLength(3); expect(first.entries[0]!.mode & 0o777).toBe(0o777);
  expect(first.entries.find(e => e.kind === "file")?.sha256).toMatch(/^[a-f0-9]{64}$/);
  writeFileSync(f.file, '{"generation":2}'); const changed = scanOwnedGeneratedCache(f.root);
  expect(changed.entries[0]!.ino).toBe(first.entries[0]!.ino); expect(changed.digest).not.toBe(first.digest);
});
test("refuses a symlink member, ancestor, and root", () => {
  const f = fixture(); symlinkSync(f.file, path.join(f.cache, "redirect")); expect(() => scanOwnedGeneratedCache(f.root)).toThrow();
  rmSync(path.join(f.cache, "redirect")); const alias = path.join(f.parent, "alias"); symlinkSync(f.parent, alias);
  expect(() => scanOwnedGeneratedCache(path.join(alias, "node_modules"))).toThrow();
  rmSync(f.root, { recursive: true }); symlinkSync(f.cache, f.root); expect(() => scanOwnedGeneratedCache(f.root)).toThrow();
});
test("refuses hardlinks even when both names and UID belong to this tree", () => {
  const f = fixture(); linkSync(f.file, path.join(f.cache, "hardlink")); expect(() => scanOwnedGeneratedCache(f.root)).toThrow("shared");
});
test("refuses arbitrary installed packages and special files instead of treating them as cache data", () => {
  const f = fixture(); mkdirSync(path.join(f.root, "package")); expect(() => scanOwnedGeneratedCache(f.root)).toThrow("Vite");
  rmdirSync(path.join(f.root, "package"));
  const result = Bun.spawnSync(["mkfifo", path.join(f.cache, "pipe")]); expect(result.exitCode).toBe(0);
  expect(() => scanOwnedGeneratedCache(f.root)).toThrow("special");
});
test("refuses files beyond the bounded data size", () => {
  const f = fixture(); writeFileSync(f.file, Buffer.alloc(16 * 1024 * 1024 + 1));
  expect(() => scanOwnedGeneratedCache(f.root)).toThrow("bound");
});
